```sql
-- =========================================================
-- GLOBAL NETWORK KENYA
-- Database Schema
-- File: backend/database/schema.sql
-- Database: PostgreSQL
-- =========================================================

BEGIN;

-- =========================================================
-- 1. USERS TABLE
-- Stores login accounts and user roles.
-- =========================================================

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(30) NOT NULL DEFAULT '',
    password_hash TEXT NOT NULL,

    role VARCHAR(20) NOT NULL DEFAULT 'user'
        CHECK (role IN ('user', 'advertiser', 'admin')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT users_name_not_empty
        CHECK (LENGTH(TRIM(name)) >= 2),

    CONSTRAINT users_email_not_empty
        CHECK (LENGTH(TRIM(email)) > 0)
);

CREATE INDEX IF NOT EXISTS idx_users_role
    ON users(role);


-- =========================================================
-- 2. BUSINESSES TABLE
-- Stores businesses submitted by users for advertising.
-- =========================================================

CREATE TABLE IF NOT EXISTS businesses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    owner_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,

    name VARCHAR(160) NOT NULL,
    category VARCHAR(100) NOT NULL,
    county VARCHAR(100) NOT NULL,

    phone VARCHAR(30) NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT '',
    image_url TEXT,

    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'published', 'rejected')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT businesses_name_not_empty
        CHECK (LENGTH(TRIM(name)) > 0),

    CONSTRAINT businesses_category_not_empty
        CHECK (LENGTH(TRIM(category)) > 0),

    CONSTRAINT businesses_county_not_empty
        CHECK (LENGTH(TRIM(county)) > 0)
);

CREATE INDEX IF NOT EXISTS idx_businesses_owner
    ON businesses(owner_id);

CREATE INDEX IF NOT EXISTS idx_businesses_status
    ON businesses(status);

CREATE INDEX IF NOT EXISTS idx_businesses_category
    ON businesses(category);

CREATE INDEX IF NOT EXISTS idx_businesses_county
    ON businesses(county);


-- =========================================================
-- 3. PACKAGES TABLE
-- Stores advertising packages available to customers.
-- Prices below are illustrative Kenyan shilling prices.
-- =========================================================

CREATE TABLE IF NOT EXISTS packages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT NOT NULL DEFAULT '',

    price NUMERIC(12, 2) NOT NULL
        CHECK (price >= 0),

    currency VARCHAR(3) NOT NULL DEFAULT 'KES'
        CHECK (currency = 'KES'),

    duration_days INTEGER NOT NULL
        CHECK (duration_days > 0),

    placement VARCHAR(20) NOT NULL DEFAULT 'standard'
        CHECK (placement IN ('standard', 'featured', 'banner')),

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_packages_active
    ON packages(is_active);


-- =========================================================
-- 4. ADVERTS TABLE
-- Stores advertising campaigns for published businesses.
-- =========================================================

CREATE TABLE IF NOT EXISTS adverts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    business_id BIGINT NOT NULL
        REFERENCES businesses(id) ON DELETE CASCADE,

    title VARCHAR(150) NOT NULL,
    description TEXT NOT NULL DEFAULT '',

    image_url TEXT,
    target_url TEXT,

    placement VARCHAR(20) NOT NULL DEFAULT 'standard'
        CHECK (placement IN ('standard', 'featured', 'banner')),

    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),

    starts_at TIMESTAMPTZ,
    ends_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT adverts_title_not_empty
        CHECK (LENGTH(TRIM(title)) >= 3),

    CONSTRAINT adverts_valid_dates
        CHECK (
            starts_at IS NULL
            OR ends_at IS NULL
            OR ends_at > starts_at
        )
);

CREATE INDEX IF NOT EXISTS idx_adverts_business
    ON adverts(business_id);

CREATE INDEX IF NOT EXISTS idx_adverts_status
    ON adverts(status);

CREATE INDEX IF NOT EXISTS idx_adverts_placement
    ON adverts(placement);

CREATE INDEX IF NOT EXISTS idx_adverts_created
    ON adverts(created_at DESC);

CREATE INDEX IF NOT EXISTS idx_adverts_schedule
    ON adverts(starts_at, ends_at);


-- =========================================================
-- 5. PAYMENTS TABLE
-- Stores payment records and payment status.
-- Actual payment processing must be implemented separately.
-- =========================================================

CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,

    package_id BIGINT
        REFERENCES packages(id) ON DELETE SET NULL,

    amount NUMERIC(12, 2) NOT NULL
        CHECK (amount > 0),

    currency VARCHAR(3) NOT NULL DEFAULT 'KES'
        CHECK (currency = 'KES'),

    phone VARCHAR(30),

    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (
            status IN (
                'pending',
                'processing',
                'successful',
                'failed',
                'cancelled'
            )
        ),

    provider_receipt VARCHAR(150) UNIQUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_payments_user
    ON payments(user_id);

CREATE INDEX IF NOT EXISTS idx_payments_package
    ON payments(package_id);

CREATE INDEX IF NOT EXISTS idx_payments_status
    ON payments(status);

CREATE INDEX IF NOT EXISTS idx_payments_created
    ON payments(created_at DESC);


-- =========================================================
-- 6. AUTOMATIC UPDATED_AT TIMESTAMP
-- Refreshes updated_at whenever a record is updated.
-- =========================================================

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


-- Users trigger
DROP TRIGGER IF EXISTS trg_users_updated_at ON users;

CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON users
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();


-- Businesses trigger
DROP TRIGGER IF EXISTS trg_businesses_updated_at ON businesses;

CREATE TRIGGER trg_businesses_updated_at
BEFORE UPDATE ON businesses
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();


-- Packages trigger
DROP TRIGGER IF EXISTS trg_packages_updated_at ON packages;

CREATE TRIGGER trg_packages_updated_at
BEFORE UPDATE ON packages
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();


-- Adverts trigger
DROP TRIGGER IF EXISTS trg_adverts_updated_at ON adverts;

CREATE TRIGGER trg_adverts_updated_at
BEFORE UPDATE ON adverts
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();


-- Payments trigger
DROP TRIGGER IF EXISTS trg_payments_updated_at ON payments;

CREATE TRIGGER trg_payments_updated_at
BEFORE UPDATE ON payments
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();


